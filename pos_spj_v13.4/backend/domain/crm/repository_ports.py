class OpportunityProductInterestRepositoryPort(Protocol):
    def save(self, interest: OpportunityProductInterest) -> None: ...
    def list_for_opportunity(self, opportunity_id: str) -> list[OpportunityProductInterest]: ...


class CRMActivityRepositoryPort(Protocol):
    def save(self, activity: CRMActivity, *, operation_id: str | None = None) -> None: ...
